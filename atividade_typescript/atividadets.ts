// Função de multiplicação
function multiplicar(a: number, b: number): number {
    return a * b;
}

// Função de saudação
function saudar(nome: string): string {
    return "Olá, " + nome;
}

// Testando as funções
console.log(multiplicar(3, 4)); // Saída: 12
console.log(saudar("José"));   // Saída: Olá José
